/** 按 id 取内置人设。 */
export function getBuiltinPersona(id: string): Persona | undefined {
  return BUILTIN_PERSONAS.find((persona) => persona.id === id);
}

/** 是否是内置人设 id。 */
export function isBuiltinPersonaId(id: string): boolean {
  return BUILTIN_PERSONAS.some((persona) => persona.id === id);
}

